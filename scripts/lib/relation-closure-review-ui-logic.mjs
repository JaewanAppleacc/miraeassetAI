// takes plain data in and returns plain data out.
//
// This UI reviews AMENDS/TERMINATES relation CANDIDATES (which document
// pair is really connected), never a Gold answer -- see FINAL_EXPORT_FILENAME
// and the disposition vocabulary below (CONFIRM/REJECT/NEEDS_MORE_REVIEW,
// not APPROVE/FIX_REQUIRED/REJECT_RESPONSE).
export const LOGIC_SCRIPT = [
"// === LOGIC_START ===",
"var FINAL_EXPORT_FILENAME = 'relation-closure-owner-decision.v0.1.jsonl';",
"var DRAFT_EXPORT_FILENAME = 'relation-closure-owner-decision-draft.jsonl';",
"",
"function buildInitialReviewState(rowIds) {",
"  var state = {};",
"  for (var i = 0; i < rowIds.length; i++) {",
"    state[rowIds[i]] = { owner_disposition: 'PENDING', confirmed_target_document_id: null, notes: '', reviewer: null, reviewed_at: null };",
"  }",
"  return state;",
"}",
"",
"// Pure -- returns a NEW reviewState, never mutates the input.",
"function applyDecision(reviewState, rowId, disposition, confirmedTargetDocumentId, nowIso, reviewerName) {",
"  var next = {};",
"  for (var k in reviewState) if (Object.prototype.hasOwnProperty.call(reviewState, k)) next[k] = reviewState[k];",
"  var prior = next[rowId] || { notes: '' };",
"  next[rowId] = {",
"    owner_disposition: disposition,",
"    confirmed_target_document_id: disposition === 'CONFIRM' ? confirmedTargetDocumentId : null,",
"    reviewer: reviewerName || null,",
"    reviewed_at: nowIso,",
"    notes: prior.notes != null ? prior.notes : '',",
"  };",
"  return next;",
"}",
"",
"function allJudged(reviewState, rowIds) {",
"  for (var i = 0; i < rowIds.length; i++) {",
"    var entry = reviewState[rowIds[i]];",
"    if (!entry || entry.owner_disposition === 'PENDING') return false;",
"  }",
"  return true;",
"}",
"",
"function judgedCount(reviewState, rowIds) {",
"  var n = 0;",
"  for (var i = 0; i < rowIds.length; i++) {",
"    var entry = reviewState[rowIds[i]];",
"    if (entry && entry.owner_disposition !== 'PENDING') n++;",
"  }",
"  return n;",
"}",
"",
"function buildFinalRecord(rowId, reviewState, rowsById, sourceMeta) {",
"  var row = rowsById[rowId];",
"  var entry = reviewState[rowId] || { owner_disposition: 'PENDING', confirmed_target_document_id: null, reviewer: null, reviewed_at: null, notes: '' };",
"  return {",
"    relation_candidate_id: rowId,",
"    source_document_id: row ? row.source_document_id : null,",
"    relation_type: row ? row.relation_type : null,",
"    source_packet_path: sourceMeta.source_packet_path,",
"    source_packet_sha256: sourceMeta.source_packet_sha256,",
"    owner_disposition: entry.owner_disposition,",
"    confirmed_target_document_id: entry.confirmed_target_document_id,",
"    reviewer: entry.reviewer,",
"    reviewed_at: entry.reviewed_at,",
"    notes: entry.notes,",
"  };",
"}",
"",
"function buildExportLines(reviewState, rowsById, sourceMeta, rowIds) {",
"  var lines = [];",
"  for (var i = 0; i < rowIds.length; i++) {",
"    lines.push(JSON.stringify(buildFinalRecord(rowIds[i], reviewState, rowsById, sourceMeta)));",
"  }",
"  return lines.join('\\n') + '\\n';",
"}",
"// === LOGIC_END ===",
].join("\n");
