// Turn N4.5: PURE logic only -- no document/window/localStorage/fetch
// access anywhere in this block. Identical disposition rules/validation
// to the v0.1 Owner UI (scripts/lib/relation-closure-owner-review-ui-logic.mjs)
// -- CONFIRM requires a candidate-membership target, REJECT/NEEDS_MORE_REVIEW
// force a null target, and a non-empty owner note is always required. Only
// the export filenames differ (this is the v0.2, 30-row target set: the
// existing 29-row Owner union plus the 1 audit-conflict row from Turn N4.5).
export const LOGIC_SCRIPT = [
"// === LOGIC_START ===",
"var FINAL_EXPORT_FILENAME = 'relation-closure-owner-decision.v0.2.jsonl';",
"var DRAFT_EXPORT_FILENAME = 'relation-closure-owner-decision-draft.v0.2.jsonl';",
"",
"function buildInitialReviewState(rowIds) {",
"  var state = {};",
"  for (var i = 0; i < rowIds.length; i++) {",
"    state[rowIds[i]] = { owner_disposition: 'PENDING', confirmed_target_document_id: null, owner_note: '', owner: null, reviewed_at: null };",
"  }",
"  return state;",
"}",
"",
"// A decision is valid only if: disposition is one of the three allowed",
"// values; CONFIRM carries a non-empty confirmed_target_document_id that",
"// is actually one of this row's own candidate ids (never an arbitrary",
"// string); REJECT/NEEDS_MORE_REVIEW carry a null target; and the Owner",
"// note is non-empty (never whitespace-only) regardless of disposition.",
"function validateDecisionInput(disposition, confirmedTargetDocumentId, note, candidateIds) {",
"  if (['CONFIRM', 'REJECT', 'NEEDS_MORE_REVIEW'].indexOf(disposition) === -1) return { valid: false, reason: 'unknown disposition' };",
"  if (!note || note.trim() === '') return { valid: false, reason: 'owner note is required' };",
"  if (disposition === 'CONFIRM') {",
"    if (!confirmedTargetDocumentId) return { valid: false, reason: 'CONFIRM requires a confirmed_target_document_id' };",
"    if (candidateIds && candidateIds.indexOf(confirmedTargetDocumentId) === -1) return { valid: false, reason: 'confirmed_target_document_id must be one of this row\\'s own candidates' };",
"  } else if (confirmedTargetDocumentId) {",
"    return { valid: false, reason: disposition + ' must not carry a confirmed_target_document_id' };",
"  }",
"  return { valid: true, reason: null };",
"}",
"",
"// Pure -- returns a NEW reviewState, never mutates the input. Throws if",
"// the input itself is invalid (defense in depth).",
"function applyOwnerDecision(reviewState, rowId, disposition, confirmedTargetDocumentId, note, nowIso, ownerName, candidateIds) {",
"  var check = validateDecisionInput(disposition, confirmedTargetDocumentId, note, candidateIds);",
"  if (!check.valid) throw new Error('invalid owner decision for ' + rowId + ': ' + check.reason);",
"  var next = {};",
"  for (var k in reviewState) if (Object.prototype.hasOwnProperty.call(reviewState, k)) next[k] = reviewState[k];",
"  next[rowId] = {",
"    owner_disposition: disposition,",
"    confirmed_target_document_id: disposition === 'CONFIRM' ? confirmedTargetDocumentId : null,",
"    owner_note: note,",
"    owner: ownerName || null,",
"    reviewed_at: nowIso,",
"  };",
"  return next;",
"}",
"",
"function allJudged(reviewState, rowIds) {",
"  for (var i = 0; i < rowIds.length; i++) {",
"    var entry = reviewState[rowIds[i]];",
"    if (!entry || entry.owner_disposition === 'PENDING') return false;",
"  }",
"  return true;",
"}",
"",
"function judgedCount(reviewState, rowIds) {",
"  var n = 0;",
"  for (var i = 0; i < rowIds.length; i++) {",
"    var entry = reviewState[rowIds[i]];",
"    if (entry && entry.owner_disposition !== 'PENDING') n++;",
"  }",
"  return n;",
"}",
"",
"function buildFinalRecord(rowId, reviewState, rowsById) {",
"  var row = rowsById[rowId];",
"  var entry = reviewState[rowId] || { owner_disposition: 'PENDING', confirmed_target_document_id: null, owner_note: '', owner: null, reviewed_at: null };",
"  return {",
"    relation_candidate_id: rowId,",
"    relation_type: row ? row.relation_type : null,",
"    source_document_id: row ? row.source_document_id : null,",
"    owner_review_reason: row ? row.owner_review_reason : null,",
"    reviewer_a_disposition: row ? row.reviewer_a.owner_disposition : null,",
"    reviewer_a_target: row ? row.reviewer_a.confirmed_target_document_id : null,",
"    reviewer_b_disposition: row ? row.reviewer_b.owner_disposition : null,",
"    reviewer_b_target: row ? row.reviewer_b.confirmed_target_document_id : null,",
"    owner_disposition: entry.owner_disposition,",
"    confirmed_target_document_id: entry.confirmed_target_document_id,",
"    owner_note: entry.owner_note,",
"    owner: entry.owner,",
"    reviewed_at: entry.reviewed_at,",
"  };",
"}",
"",
"function buildExportLines(reviewState, rowsById, rowIds) {",
"  var lines = [];",
"  for (var i = 0; i < rowIds.length; i++) {",
"    lines.push(JSON.stringify(buildFinalRecord(rowIds[i], reviewState, rowsById)));",
"  }",
"  return lines.join('\\n') + '\\n';",
"}",
"// === LOGIC_END ===",
].join("\n");
