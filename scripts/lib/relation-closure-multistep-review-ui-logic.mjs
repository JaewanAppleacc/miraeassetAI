// Turn N4.5, Task 7: PURE logic only -- no document/window/localStorage/
// fetch access anywhere in this block. This UI reviews the multi-step
// correction RISK packet (a risk-DETECTION output, never an automatic
// verdict) with the same CONFIRM/REJECT/NEEDS_MORE_REVIEW vocabulary as
// the Owner/Reviewer A-B UIs. CONFIRM's target must be one of the row's
// own presented candidate/related-document union -- never an arbitrary
// string. Two independent reviewer roles (REVIEWER_C / REVIEWER_D) are
// resolved to entirely separate export filenames, mirroring
// scripts/lib/relation-closure-review-ui-logic.mjs's resolveExportFilenames
// pattern, so neither reviewer's file/localStorage can collide with the
// other's or with any Owner/Auditor/Reviewer-A/B namespace.
export const LOGIC_SCRIPT = [
"// === LOGIC_START ===",
"var FINAL_EXPORT_FILENAME = 'relation-multistep-reviewer-decision.v0.1.jsonl';",
"var DRAFT_EXPORT_FILENAME = 'relation-multistep-reviewer-decision-draft.v0.1.jsonl';",
"",
"function resolveExportFilenames(reviewerRole) {",
"  if (reviewerRole === 'REVIEWER_C') {",
"    return { final: 'relation-multistep-reviewer-c-decision.v0.1.jsonl', draft: 'relation-multistep-reviewer-c-decision-draft.v0.1.jsonl' };",
"  }",
"  if (reviewerRole === 'REVIEWER_D') {",
"    return { final: 'relation-multistep-reviewer-d-decision.v0.1.jsonl', draft: 'relation-multistep-reviewer-d-decision-draft.v0.1.jsonl' };",
"  }",
"  return { final: FINAL_EXPORT_FILENAME, draft: DRAFT_EXPORT_FILENAME };",
"}",
"",
"function buildInitialReviewState(rowIds) {",
"  var state = {};",
"  for (var i = 0; i < rowIds.length; i++) {",
"    state[rowIds[i]] = { reviewer_disposition: 'PENDING', confirmed_target_document_id: null, reviewer_note: '', reviewer: null, reviewed_at: null };",
"  }",
"  return state;",
"}",
"",
"// A decision is valid only if: disposition is one of the three allowed",
"// values; CONFIRM carries a non-empty confirmed_target_document_id that",
"// is one of this row's own presented candidate/related-document union",
"// (never an arbitrary string); REJECT/NEEDS_MORE_REVIEW carry a null",
"// target; and the reviewer note is non-empty (never whitespace-only).",
"function validateDecisionInput(disposition, confirmedTargetDocumentId, note, candidateUnionIds) {",
"  if (['CONFIRM', 'REJECT', 'NEEDS_MORE_REVIEW'].indexOf(disposition) === -1) return { valid: false, reason: 'unknown disposition' };",
"  if (!note || note.trim() === '') return { valid: false, reason: 'reviewer note is required' };",
"  if (disposition === 'CONFIRM') {",
"    if (!confirmedTargetDocumentId) return { valid: false, reason: 'CONFIRM requires a confirmed_target_document_id' };",
"    if (candidateUnionIds && candidateUnionIds.indexOf(confirmedTargetDocumentId) === -1) return { valid: false, reason: 'confirmed_target_document_id must be within this row\\'s own candidate/related-document union' };",
"  } else if (confirmedTargetDocumentId) {",
"    return { valid: false, reason: disposition + ' must not carry a confirmed_target_document_id' };",
"  }",
"  return { valid: true, reason: null };",
"}",
"",
"// Pure -- returns a NEW reviewState, never mutates the input.",
"function applyReviewerDecision(reviewState, rowId, disposition, confirmedTargetDocumentId, note, nowIso, reviewerName, candidateUnionIds) {",
"  var check = validateDecisionInput(disposition, confirmedTargetDocumentId, note, candidateUnionIds);",
"  if (!check.valid) throw new Error('invalid reviewer decision for ' + rowId + ': ' + check.reason);",
"  var next = {};",
"  for (var k in reviewState) if (Object.prototype.hasOwnProperty.call(reviewState, k)) next[k] = reviewState[k];",
"  next[rowId] = {",
"    reviewer_disposition: disposition,",
"    confirmed_target_document_id: disposition === 'CONFIRM' ? confirmedTargetDocumentId : null,",
"    reviewer_note: note,",
"    reviewer: reviewerName || null,",
"    reviewed_at: nowIso,",
"  };",
"  return next;",
"}",
"",
"function allJudged(reviewState, rowIds) {",
"  for (var i = 0; i < rowIds.length; i++) {",
"    var entry = reviewState[rowIds[i]];",
"    if (!entry || entry.reviewer_disposition === 'PENDING') return false;",
"  }",
"  return true;",
"}",
"",
"function judgedCount(reviewState, rowIds) {",
"  var n = 0;",
"  for (var i = 0; i < rowIds.length; i++) {",
"    var entry = reviewState[rowIds[i]];",
"    if (entry && entry.reviewer_disposition !== 'PENDING') n++;",
"  }",
"  return n;",
"}",
"",
"function buildFinalRecord(rowId, reviewState, rowsById, sourceMeta) {",
"  var row = rowsById[rowId];",
"  var entry = reviewState[rowId] || { reviewer_disposition: 'PENDING', confirmed_target_document_id: null, reviewer_note: '', reviewer: null, reviewed_at: null };",
"  return {",
"    relation_candidate_id: rowId,",
"    source_document_id: row ? row.source_document_id : null,",
"    relation_type: row ? row.relation_type : null,",
"    risk_reason: row ? row.risk_reason : null,",
"    source_risk_packet_path: sourceMeta.source_risk_packet_path,",
"    source_risk_packet_sha256: sourceMeta.source_risk_packet_sha256,",
"    reviewer_role: sourceMeta.reviewer_role || null,",
"    reviewer_disposition: entry.reviewer_disposition,",
"    confirmed_target_document_id: entry.confirmed_target_document_id,",
"    reviewer_note: entry.reviewer_note,",
"    reviewer: entry.reviewer,",
"    reviewed_at: entry.reviewed_at,",
"  };",
"}",
"",
"function buildExportLines(reviewState, rowsById, sourceMeta, rowIds) {",
"  var lines = [];",
"  for (var i = 0; i < rowIds.length; i++) {",
"    lines.push(JSON.stringify(buildFinalRecord(rowIds[i], reviewState, rowsById, sourceMeta)));",
"  }",
"  return lines.join('\\n') + '\\n';",
"}",
"// === LOGIC_END ===",
].join("\n");
