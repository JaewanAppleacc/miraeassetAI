// Turn M5 Section 7A: a NEW ontology proposal review UI revision (v0.2)
// -- never overwrites v0.1's UI. 5 cards (packet v0.2), each showing the
// EXACT Candidate preview record(s) that would be authored on approval
// (linked from seed-structured-gap-candidate-preview.v0.1.jsonl), so the
// Owner judges the token AND its real resulting record together. If a
// card is REJECTed, its dependent preview(s) are shown as
// BLOCKED_BY_ONTOLOGY_DECISION in the UI -- this is a DISPLAY-only
// computed label; it never writes back into or mutates the card's own
// owner_disposition value. All PENDING by default, no AI auto-approval.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PACKET_PATH = path.join(REPO, "work/handoff/seed-final-response-owner-review/results/seed-response-ontology-proposal-decision-packet.v0.2.json");
const PREVIEW_PATH = path.join(REPO, "work/domain-seed/seed-structured-gap-candidate-preview.v0.1.jsonl");
const OUT_DIR = path.join(REPO, "work/handoff/seed-final-response-owner-review/ui/ontology-proposals-v0.2");
const OUT_HTML_PATH = path.join(OUT_DIR, "seed-response-ontology-proposal-review.html");
const OUT_REPORT_PATH = path.join(OUT_DIR, "review-ui-build-report.json");
const FINAL_EXPORT_FILENAME = "seed-response-ontology-proposal-owner-decision.v0.2.jsonl";

function sha256(bytes) { return createHash("sha256").update(bytes).digest("hex"); }
function jsonl(text) { return text.trim().split("\n").map((l) => JSON.parse(l)); }
function escapeForScriptEmbed(jsonText) {
  return jsonText.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");
}

async function main() {
  const packetBytes = await readFile(PACKET_PATH);
  const packet = JSON.parse(packetBytes.toString("utf8"));
  const previewBytes = await readFile(PREVIEW_PATH);
  const previewRows = jsonl(previewBytes.toString("utf8"));
  const previewsByCardId = new Map();
  for (const row of previewRows) {
    const list = previewsByCardId.get(row.ontology_proposal_card_id) ?? [];
    list.push(row);
    previewsByCardId.set(row.ontology_proposal_card_id, list);
  }

  const cards = packet.cards.map((c) => ({
    ...c,
    dependent_previews: (previewsByCardId.get(c.card_id) ?? []).map((p) => ({
      fact_id: p.fact.fact_id, metric_code: p.fact.metric_code, raw_label: p.fact.raw_label,
      normalized_value: p.fact.normalized_value, unit: p.fact.unit, scope: p.fact.scope,
      period_type: p.fact.period_type, as_of_date: p.fact.as_of_date, source_document_id: p.fact.source_document_id,
      evidence_id: p.evidence_id, source_locator: p.source_locator, quoted_text: p.quoted_text,
      linked_existing_fact_id: p.linked_existing_fact_id, previous_decision_note: p.previous_decision_note,
    })),
  }));

  const payload = {
    schema_version: "0.2.0",
    generated_at: new Date().toISOString(),
    source_packet_path: "work/handoff/seed-final-response-owner-review/results/seed-response-ontology-proposal-decision-packet.v0.2.json",
    source_packet_sha256: sha256(packetBytes),
    source_preview_path: "work/domain-seed/seed-structured-gap-candidate-preview.v0.1.jsonl",
    source_preview_sha256: sha256(previewBytes),
    final_export_filename: FINAL_EXPORT_FILENAME,
    cards,
  };

  const html = buildHtml(payload);
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(OUT_HTML_PATH, html, "utf8");

  const htmlBytes = Buffer.from(html, "utf8");
  const report = {
    schema_version: "0.2.0",
    generated_at: payload.generated_at,
    output_html_path: path.relative(REPO, OUT_HTML_PATH),
    output_html_sha256: sha256(htmlBytes),
    card_count: cards.length,
    dependent_preview_total: cards.reduce((n, c) => n + c.dependent_previews.length, 0),
    final_export_filename: FINAL_EXPORT_FILENAME,
  };
  await writeFile(OUT_REPORT_PATH, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  console.log(JSON.stringify({ output_html_sha256: report.output_html_sha256, card_count: cards.length, dependent_preview_total: report.dependent_preview_total }, null, 2));
}

